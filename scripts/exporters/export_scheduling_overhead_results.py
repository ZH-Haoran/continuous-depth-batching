"""Export the scheduling-control idle fractions as LaTeX macros for the paper.

The inputs are analyzed Nsight JSON files written by ``scripts/analyze_paper_nsys.py``.
Each input must contain one warning-free ``benchmark.steady`` range.

Example:
    uv run python scripts/exporters/export_scheduling_overhead_results.py \
        --sync outputs/ablations/scheduling-overhead/sync_analysis.json \
        --async-immediate outputs/ablations/scheduling-overhead/async_analysis.json \
        --lookahead outputs/ablations/scheduling-overhead/lookahead_analysis.json \
        --output docs/paper/figs/cdb_async_overhead_data.tex
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any

VARIANTS = (
    ("sync", "idleSync"),
    ("async_immediate", "idleAsyncImmediate"),
    ("lookahead", "idleLookahead"),
)


def load_idle_percent(path: Path, *, expected_label: str) -> float:
    """Load and validate one measured steady-state GPU idle fraction."""
    payload: dict[str, Any] = json.loads(path.read_text(encoding="utf-8"))
    if payload.get("label") != expected_label:
        raise ValueError(f"{path} has label {payload.get('label')!r}; expected {expected_label!r}")
    if payload.get("measured_label") != "benchmark.steady":
        raise ValueError(f"{path} was not measured over benchmark.steady")
    if payload.get("measured_range_count") != 1:
        raise ValueError(f"{path} must contain exactly one measured range")
    warnings = payload.get("diagnostics", {}).get("warnings")
    if warnings != []:
        raise ValueError(f"{path} has capture diagnostics warnings: {warnings!r}")
    try:
        fraction = float(payload["measured"]["100us"]["gpu_idle_fraction"])
    except (KeyError, TypeError, ValueError) as error:
        raise ValueError(f"{path} has no valid 100us GPU idle fraction") from error
    if not 0.0 <= fraction <= 1.0:
        raise ValueError(f"{path} has invalid GPU idle fraction {fraction}")
    return 100.0 * fraction


def render_macros(values: dict[str, float]) -> str:
    """Render plot values and two-decimal labels from the validated percentages."""
    lines = ["% Generated by scripts/exporters/export_scheduling_overhead_results.py."]
    for key, macro in VARIANTS:
        value = values[key]
        lines.append(f"\\def\\{macro}{{{value:.3f}}}")
        lines.append(f"\\def\\{macro}Label{{{value:.2f}\\%}}")
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--sync", type=Path, required=True)
    parser.add_argument("--async-immediate", type=Path, required=True)
    parser.add_argument("--lookahead", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    values = {
        "sync": load_idle_percent(args.sync, expected_label="sync"),
        "async_immediate": load_idle_percent(args.async_immediate, expected_label="async"),
        "lookahead": load_idle_percent(args.lookahead, expected_label="lookahead"),
    }
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(render_macros(values), encoding="utf-8")
    print(f"Wrote {args.output}")


if __name__ == "__main__":
    main()
